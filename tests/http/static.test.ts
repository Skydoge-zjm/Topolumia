import test from "node:test";
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { sendStatic } from "../../src/http/static.js";

test("static responses negotiate compression, validate caches and retain HEAD semantics", async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), "topolumia-static-"));
  await mkdir(path.join(root, "assets"));
  const content = "console.log('synthetic resource');\n".repeat(1000);
  await writeFile(path.join(root, "assets", "app-123abc45.js"), content);
  await writeFile(path.join(root, "index.html"), "<html>" + "workspace ".repeat(500) + "</html>");
  const server = createServer((request, response) => { void sendStatic(request, response, root, new URL(request.url, "http://localhost").pathname).catch(error => { response.writeHead(error.status ?? 500); response.end(); }); });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await rm(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  const compressed = await fetch(base + "/assets/app-123abc45.js", { headers: { "accept-encoding": "br, gzip" } });
  assert.equal(compressed.headers.get("content-encoding"), "br");
  assert.equal(compressed.headers.get("vary"), "Accept-Encoding");
  assert.match(compressed.headers.get("cache-control"), /immutable/);
  assert.ok(Number(compressed.headers.get("content-length")) < content.length / 2);
  assert.equal(await compressed.text(), content);
  const etag = compressed.headers.get("etag");
  const unchanged = await fetch(base + "/assets/app-123abc45.js", { headers: { "accept-encoding": "br", "if-none-match": "W/" + etag } });
  assert.equal(unchanged.status, 304);
  assert.equal(await unchanged.text(), "");
  const identity = await fetch(base + "/assets/app-123abc45.js", { headers: { "accept-encoding": "br;q=0,gzip;q=0,identity;q=1", "if-none-match": etag } });
  assert.equal(identity.status, 200);
  assert.equal(identity.headers.get("content-encoding"), null);
  assert.notEqual(identity.headers.get("etag"), etag);
  assert.equal(await identity.text(), content);
  const head = await fetch(base + "/assets/app-123abc45.js", { method: "HEAD", headers: { "accept-encoding": "identity" } });
  assert.equal(Number(head.headers.get("content-length")), Buffer.byteLength(content));
  assert.equal(await head.text(), "");
  const html = await fetch(base + "/", { headers: { "accept-encoding": "gzip" } });
  assert.equal(html.headers.get("cache-control"), "no-cache");
  assert.equal(html.headers.get("content-encoding"), "gzip");
  await html.text();
  const modifiedSince = await fetch(base + "/", { headers: { "if-modified-since": html.headers.get("last-modified") } });
  assert.equal(modifiedSince.status, 304);
  await writeFile(path.join(root, "index.html"), "<html>Updated workspace</html>");
  const changed = await fetch(base + "/", { headers: { "if-none-match": html.headers.get("etag") } });
  assert.equal(changed.status, 200);
  assert.equal(await changed.text(), "<html>Updated workspace</html>");
  const unacceptable = await fetch(base + "/", { headers: { "accept-encoding": "*;q=0" } });
  assert.equal(unacceptable.status, 406);
});
